CREATE TABLE usuario (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(255) NOT NULL,
    email   VARCHAR(255) NOT NULL UNIQUE,
    senha   VARCHAR(255) NOT NULL,
    salt    VARCHAR(255) NOT NULL,
    perfil  VARCHAR(20)  NOT NULL,
    ativo   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE endereco (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cep         VARCHAR(10)  NOT NULL,
    logradouro  VARCHAR(200) NOT NULL,
    numero      VARCHAR(20)  NOT NULL,
    complemento VARCHAR(100),
    bairro      VARCHAR(100) NOT NULL,
    cidade      VARCHAR(100) NOT NULL,
    uf          VARCHAR(2)   NOT NULL
);

CREATE TABLE cliente (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(255) NOT NULL,
    cpf         VARCHAR(14)  NOT NULL UNIQUE,
    email       VARCHAR(255) NOT NULL UNIQUE,
    telefone    VARCHAR(20)  NOT NULL,
    usuario_id  BIGINT NOT NULL UNIQUE REFERENCES usuario (id),
    endereco_id BIGINT NOT NULL UNIQUE REFERENCES endereco (id)
);

CREATE TABLE funcionario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_nascimento DATE   NOT NULL,
    usuario_id      BIGINT NOT NULL UNIQUE REFERENCES usuario (id)
);

CREATE TABLE categoria (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(255) NOT NULL,
    ativo BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE solicitacao (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao_equipamento VARCHAR(255) NOT NULL,
    categoria_id          BIGINT       NOT NULL REFERENCES categoria (id),
    descricao_defeito     VARCHAR(500) NOT NULL,
    data_hora             TIMESTAMP    NOT NULL,
    estado                VARCHAR(20)  NOT NULL,
    cliente_id            BIGINT       NOT NULL REFERENCES cliente (id),
    valor_orcamento       NUMERIC(10,2),
    motivo_rejeicao       VARCHAR(500)
);

CREATE TABLE historico_solicitacao (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id     BIGINT       NOT NULL REFERENCES solicitacao (id),
    estado_anterior    VARCHAR(20),
    estado             VARCHAR(20)  NOT NULL,
    data_hora          TIMESTAMP    NOT NULL,
    usuario_id         BIGINT       NOT NULL REFERENCES usuario (id),
    usuario_destino_id BIGINT       REFERENCES usuario (id),
    observacao         VARCHAR(500),
    CONSTRAINT chk_historico_estado_anterior CHECK (estado_anterior IS NOT NULL OR estado = 'ABERTA'),
    CONSTRAINT chk_historico_destino_redirecionada CHECK (usuario_destino_id IS NULL OR estado = 'REDIRECIONADA'),
    CONSTRAINT chk_historico_destino_diferente CHECK (usuario_destino_id IS NULL OR usuario_destino_id <> usuario_id),
    CONSTRAINT chk_historico_observacao_rejeitada CHECK (estado <> 'REJEITADA' OR (observacao IS NOT NULL AND length(trim(observacao)) > 0))
);

CREATE INDEX idx_historico_solicitacao_data_hora ON historico_solicitacao (solicitacao_id, data_hora);

